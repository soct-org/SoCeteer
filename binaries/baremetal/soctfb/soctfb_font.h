static const uint8_t soctfb_font_box[8] = {0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00};

static inline const uint8_t *soctfb_glyph(char c) {
    if (c >= '0' && c <= '9') return soctfb_font_digits[c - '0'];
    if (c >= 'A' && c <= 'Z') return soctfb_font_upper[c - 'A'];
    if (c >= 'a' && c <= 'z') return soctfb_font_upper[c - 'a'];
    switch (c) {
    case ' ': return soctfb_font_punct[0];
    case '.': return soctfb_font_punct[1];
    case '%': return soctfb_font_punct[2];
    case ':': return soctfb_font_punct[3];
    case '-': return soctfb_font_punct[4];
    case ',': return soctfb_font_punct[5];
    case '/': return soctfb_font_punct[6];
    default: return soctfb_font_box;
    }
}

